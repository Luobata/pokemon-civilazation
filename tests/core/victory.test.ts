test('HQ capture atomically transfers, neutralizes, removes all units, freezes zero-city score', () => {
  const state = combatFixture(); state.players[0].controller = 'ai';
  state.players[2] = { ...structuredClone(state.players[1]), id: 2, headquartersCityId: 4 };
  state.knowledge[2] = structuredClone(state.knowledge[1]); state.turnOrder.push(2);
  state.cities[3] = createCity(3, 1, { q: 5, r: 6 }); state.cities[4] = createCity(4, 2, { q: 12, r: 5 });
  state.cities[3].queue = [{ id: 50, progress: 0, item: { kind: 'logistics', defId: 'settler' } }];
  pokemon(state, 10, 'charmander', 0, 9, 2); pokemon(state, 11, 'squirtle', 1);
  state.units[12] = { ...pokemon(state, 12, 'squirtle', 1), location: 'recovering', position: null, cityId: 3, roundsLeft: 1 };
  state.cities[2].hp = 1; state.diplomacy[0].status = 'war';
  const before = structuredClone(state);
  const next = accepted(state, { type: 'Attack', unitId: 10, target: { kind: 'city', id: 2 } });
  expect(state.cities).toEqual(before.cities); expect(state.units).toEqual(before.units);
  expect(next.cities[2].ownerId).toBe(0); expect(next.cities[3]).toMatchObject({ ownerId: null, hp: 50 });
  expect(Object.values(next.units).some(unit => unit.ownerId === 1)).toBe(false);
  expect(next.players[1].frozenScore).toMatchObject({ cities: 0, population: 0 });
  expect(next.turnOrder).toEqual([0, 2]); expect(next.outcome).toBeNull();
  const neutral = structuredClone(next.cities[3]); next.round++; resolveEconomy(next);
  expect(next.cities[3]).toEqual(neutral); expect(cityYield(next, neutral)).toEqual({ food: 0, production: 0, gold: 0, research: 0 });
  pokemon(next, 20, 'charmander', 0, 4, 6);
  const preview = previewAttack(observe(next, 0), 20, { kind: 'city', id: 3 });
  expect(preview).toMatchObject({ ok: true, counter: { trigger: 'never', damage: 0 } });
  const hit = accepted(next, { type: 'Attack', unitId: 20, target: { kind: 'city', id: 3 } });
  expect(hit.units[20].hp).toBe(next.units[20].hp);
  hit.units[20].actionLeft = 1; hit.cities[3].hp = 1;
  expect(accepted(hit, { type: 'Attack', unitId: 20, target: { kind: 'city', id: 3 } }).cities[3].ownerId).toBe(0);
  next.players[1].frozenScore!.total = 9999; finishGame(next, 'score');
  expect(next.outcome!.winners).not.toContain(1);
});
test('human HQ loss ends local game immediately', () => {
  const state = combatFixture(); state.activePlayerId = 1; state.cities[1].hp = 1;
  state.diplomacy[0].status = 'war'; pokemon(state, 10, 'charmander', 1, 3, 2);
  const next = accepted(state, { type: 'Attack', unitId: 10, target: { kind: 'city', id: 1 } });
  expect(next.outcome).toMatchObject({ kind: 'playerDefeat', winners: [] });
  expect(issue(next, { type: 'EndTurn' })).toEqual({ ok: false, reason: 'game-ended' });
});
test.each([100, 200, 300] as const)('stage 8 scores after settlement at %i boundary', limit => {
  let state = combatFixture(); state.setup.roundLimit = limit; state.round = limit - 1; state.activePlayerId = 1;
  state = accepted(state, { type: 'EndTurn' });
  expect(state.round).toBe(limit); expect(state.outcome).toBeNull();
  state = accepted(state, { type: 'SetResearch', techId: 'domestication' });
  state = accepted(state, { type: 'EndTurn' });
  expect(state.round).toBe(limit); expect(state.outcome).toBeNull();
  expect(state.activePlayerId).toBe(1);
  state = accepted(state, { type: 'SetResearch', techId: 'stoneCraft' });
  state.players[0].research.techId = 'domestication'; state.players[0].research.reserve = 20;
  state.cities[1].food = 100; pokemon(state, 10).hp = 10;
  const result = issue(state, { type: 'EndTurn' }); if (!result.ok) throw new Error(result.reason);
  const next = result.state;
  expect(next.outcome).toMatchObject({ kind: 'score', round: limit });
  expect(next.players[0].research.unlockedIds).toContain('domestication'); expect(next.cities[1].population).toBe(3);
  expect(next.units[10].hp).toBe(15); expect(next.units[10].actionLeft).toBe(0);
  expect(next.outcome!.ranking.find(score => score.playerId === 0)).toMatchObject({ population: 3, techs: 1 });
  expect(result.events.findIndex(event => event.payload.type === 'GameEnded')).toBeGreaterThan(result.events.findIndex(event => event.payload.type === 'TechCompleted'));
  expect(issue(next, { type: 'SetResearch', techId: 'stoneCraft' })).toEqual({ ok: false, reason: 'game-ended' });
});
test('score multiplier, tie breakers and shared winners', () => {
  const state = combatFixture(); state.players[0].registeredSpeciesIds = ['bulbasaur', 'charmander'];
  state.players[0].knockdownCount = 7; state.players[0].research.unlockedIds = ['leagueRules'];
  expect(scorePlayer(state, 0).total).toBe(Math.floor((80 + 20 + 10 + 20 + 14) * 1.2));
  const a = scorePlayer(state, 0);
  for (const key of ['cities', 'population', 'techs', 'knockdowns'] as const) expect(compareScores({ ...a, [key]: a[key] + 1 }, a)).toBeLessThan(0);
  state.players[0] = { ...structuredClone(state.players[1]), id: 0 };
  finishGame(state, 'score'); expect(state.outcome!.winners).toEqual([0, 1]);
});
